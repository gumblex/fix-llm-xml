"""
fix_llm_xml: Robust utility library to repair and parse malformed XML generated by Large Language Models (LLMs).

LLMs often produce XML with common errors: unescaped special characters, mismatched tags,
malformed CDATA sections, missing closing tags, broken attribute syntax, etc. This library
handles these edge cases while preserving content integrity, designed specifically for
LLM output scenarios.
"""
import re
from typing import Optional, Dict, List, Iterable, Tuple, Any, Set, NamedTuple

import xmltodict
from lxml import etree

VERSION = '1.2'

# ------------------------------
# Constant Definitions
# ------------------------------
# Standard CDATA section markers
CDATA_START = '<![CDATA['
CDATA_END = ']]>'
# Escaped sequence for CDATA_END that can be safely embedded inside CDATA sections
ESCAPED_CDATA_END = ']]]]><![CDATA[>'

# Regex for valid XML tag names (supports namespace prefixes like `ns:tag`)
TAG_NAME_RE = re.compile(
    r'[:A-Z_a-z'
    r'\u00C0-\u00D6\u00D8-\u00F6\u00F8-\u02FF'
    r'\u0370-\u037D\u037F-\u1FFF\u200C-\u200D\u2070-\u218F'
    r'\u2C00-\u2FEF\u3001-\uD7FF\uF900-\uFDCF\uFDF0-\uFFFD'
    r'\U00010000-\U000EFFFF'
    r']'
    r'[:A-Z_a-z0-9.\-'
    r'\u00B7\u00C0-\u00D6\u00D8-\u00F6\u00F8-\u02FF'
    r'\u0300-\u036F\u0370-\u037D\u037F-\u1FFF'
    r'\u200C-\u200D\u203F-\u2040\u2070-\u218F'
    r'\u2C00-\u2FEF\u3001-\uD7FF\uF900-\uFDCF\uFDF0-\uFFFD'
    r'\U00010000-\U000EFFFF'
    r']*'
)
# Compatible CDATA opening prefix, matched immediately after a start tag
CDATA_PREFIX_RE = re.compile(r'[<\[({!]{1,4}CDATA[\[({>]', re.IGNORECASE)
# CDATA-like prefix matched at plain content positions. Unlike CDATA_PREFIX_RE it never
# ends with '>', so legitimate tags such as <cdata> are never mistaken for a CDATA prefix.
CDATA_TEXT_PREFIX_RE = re.compile(r'[<\[({!]{1,4}CDATA[\[({]', re.IGNORECASE)
# Regex to detect valid XML entities (e.g. &lt;, &#160;, &#xA0;)
XML_ENTITY_RE = re.compile(r'&(?:#[0-9]{1,6}|#x[0-9a-fA-F]{1,6}|amp|lt|gt|quot|apos);')
# Trailing "correct or wrongly written CDATA end" residue immediately before a closing tag
TRAILING_CDATA_END_RE = re.compile(r'(?:</CDATA>|\]{1,2}\s*>{1,2})\s*$', re.IGNORECASE)

def _is_valid_tag_name(name: str) -> bool:
    """
    Reject names that cannot be safely serialized as an lxml-compatible QName.
    """
    if not name:
        return False
    parts = name.split(':')
    if len(parts) > 2:
        return False
    for part in parts:
        if not part:
            return False
        if part[0] == ':' or not _is_xml_name_start_char(part[0]):
            return False
        for c in part[1:]:
            if c == ':' or not _is_xml_name_char(c):
                return False
    return True


def _is_xml_name_start_char(ch: str) -> bool:
    if len(ch) != 1:
        return False

    o = ord(ch)
    return (
        o == 0x3A or  # :
        o == 0x5F or  # _
        0x41 <= o <= 0x5A or        # A-Z
        0x61 <= o <= 0x7A or        # a-z
        0xC0 <= o <= 0xD6 or
        0xD8 <= o <= 0xF6 or
        0xF8 <= o <= 0x2FF or
        0x370 <= o <= 0x37D or
        0x37F <= o <= 0x1FFF or
        0x200C <= o <= 0x200D or
        0x2070 <= o <= 0x218F or
        0x2C00 <= o <= 0x2FEF or
        0x3001 <= o <= 0xD7FF or
        0xF900 <= o <= 0xFDCF or
        0xFDF0 <= o <= 0xFFFD or
        0x10000 <= o <= 0xEFFFF
    )


def _is_xml_name_char(ch: str) -> bool:
    if len(ch) != 1:
        return False

    o = ord(ch)
    return (
        _is_xml_name_start_char(ch)
        or o == 0x2D      # -
        or o == 0x2E      # .
        or 0x30 <= o <= 0x39  # 0-9
        or o == 0xB7
        or 0x300 <= o <= 0x36F
        or 0x203F <= o <= 0x2040
    )

# ------------------------------
# Data Structures
# ------------------------------
class Token(NamedTuple):
    kind: str
    name: Optional[str]
    start: int
    end: int


class TextSegment:
    __slots__ = ('text', 'is_cdata', 'raw')

    def __init__(self, text: str, is_cdata: bool = False, raw: bool = False):
        self.text = text
        self.is_cdata = is_cdata
        self.raw = raw


class Node:
    __slots__ = (
        'name', 'start_tag', 'attrs', 'parent', 'children',
        'is_text_tag', 'cdata_start', 'cdata_open_prefix',
        'content_pos', 'in_cdata', 'segments',
        'explicit_close', 'auto_closed',
    )

    def __init__(self, name: str, start_tag: str, parent: Optional['Node'] = None,
                 attrs: Optional[Dict[str, str]] = None):
        self.name = name
        # Fixed, well-formed start tag string rebuilt from name + standardized attrs
        self.start_tag = start_tag
        self.attrs: Dict[str, str] = attrs if attrs is not None else {}
        self.parent = parent
        self.children: List[Any] = []
        self.is_text_tag = False
        self.cdata_start = False
        self.cdata_open_prefix = ''
        self.content_pos = 0
        self.in_cdata = False
        self.segments: List[TextSegment] = []
        self.explicit_close = False
        self.auto_closed = False


