def find_xml_document(s: str, root: str, with_tag: bool = False, cdata: bool = False) -> Optional[str]:
    """
    Extract content inside <{root}> tags from LLM-generated text, ignoring attributes and invalid formatting.

    This function is fault-tolerant and works even when the XML is partially malformed, or wrapped
    in extra non-XML text.

    Args:
        s: Input string containing (possibly malformed) XML
        root: Name of the target root tag to extract
        with_tag: If True, return the full content including the opening and closing <root> tags
        cdata: If True, expect content inside the root tag to be wrapped in <![CDATA[...]]>

    Returns:
        Extracted content string if tag is found, None otherwise. If closing tag is not found,
        returns all content after the opening tag.
    """
    start_pattern = rf'<{root}(\s+[^>]*)?>'
    if cdata:
        start_pattern += r'<!\[CDATA\['
    start_match = re.search(start_pattern, s, re.DOTALL)

    if not start_match:
        return None

    start_tag_end = start_match.end()
    start_pos = start_match.start() if with_tag else start_tag_end

    # Search for closing tag from end of string to handle nested tags with same name
    end_tag = f'</{root}>'
    if cdata:
        end_tag = CDATA_END + end_tag
    end_pos = s.rfind(end_tag)

    # If closing tag not found or appears before opening tag, return all content after opening tag
    if end_pos < start_tag_end:
        return s[start_pos:]

    if with_tag:
        end_pos += len(end_tag)
    return s[start_pos:end_pos]


def parse_xml(
    s: str, root: str,
    text_tags: Optional[List[str]] = None,
    **kwargs
) -> Optional[Dict]:
    """
    Parse LLM-generated XML string into a Python dictionary, with auto-repair for common errors.

    Will automatically attempt to fix malformed XML before parsing if initial parsing fails.

    Args:
        s: Input string containing XML
        root: Name of the expected root tag
        text_tags: List of known plain-text tags (tags that contain no child tags, only text content)
        **kwargs: Additional parameters passed to `xmltodict.parse`, common options:
            force_list (List[str]): Force specified tags to be parsed as lists even if only one instance exists
            strip_whitespace (bool): If True, strip leading/trailing whitespace from text values, default True

    Returns:
        Parsed dictionary on success, None if parsing fails even after repair attempts
    """
    xml_str = find_xml_document(s, root, with_tag=True)
    if not xml_str:
        return None

    text_tags_set = set(text_tags or [])
    parse_kwargs = {
        'process_namespaces': False,
        'disable_entities': True,
    }
    parse_kwargs.update(kwargs)

    parsed = None
    try:
        parsed = xmltodict.parse(xml_str, **parse_kwargs)
        if not (
            text_tags_set
            and _parsed_dict_has_nested_text_tags(parsed, text_tags_set)
        ):
            return parsed
    except Exception:
        parsed = None

    fixed = fix_xml_with_text_tags(xml_str, text_tags_set)

    try:
        root_elem = etree.fromstring(
            fixed,
            parser=etree.XMLParser(
                recover=True,
                resolve_entities=False,
                no_network=True,
            ),
        )
        fixed_xml = etree.tostring(root_elem, encoding='unicode')
        return xmltodict.parse(fixed_xml, **parse_kwargs)
    except Exception:
        return parsed


def fix_xml_with_text_tags(xml: str, text_tags: Iterable[str] = ()) -> str:
    """
    Repair malformed XML via a single fault-tolerant tree construction (design §4-§8).

    Handles the following common LLM XML errors:
    - Unescaped special characters (<, >, &) in plain text content
    - Malformed CDATA sections (CDATA start tags, native CDATA blocks, missing `]]>`)
    - Mismatched/extra closing tags, missing closing tags
    - Invalid tag syntax
    - Broken attribute syntax: unclosed quotes, unquoted values, stray quotes or
      illegal characters in attribute names, duplicated attributes, attributes on
      closing tags

    Args:
        xml: Input malformed XML string
        text_tags: List of plain text tag names (case-sensitive, supports namespaces).

    Returns:
        Valid, well-formed XML string
    """
    text_tags_set = set(text_tags)

    tokens = _tokenize(xml)
    _, closes_of = _index_tokens(tokens)

    doc = Node('document', '', None)
    stack = [doc]
    pos = 0
    n = len(xml)

    while pos < n:
        top = stack[-1]

        # Text tag (pure text tag or CDATA start tag): its whole content is
        # consumed by dedicated rules (design §6 / §7)
        if top.is_text_tag:
            if top.cdata_start:
                new_pos = _consume_cdata_start_tag(xml, top, tokens, closes_of)
            else:
                new_pos = _consume_text_tag(xml, top, tokens, closes_of)
            stack.pop()
            pos = new_pos
            continue

        lt = xml.find('<', pos)
        if lt == -1:
            if pos < n:
                _append_text_segment(top, xml[pos:n])
            pos = n
            break

        if lt > pos:
            _append_text_segment(top, xml[pos:lt])
            pos = lt

        # Native legal CDATA section inside a structural node is preserved
        if xml.startswith(CDATA_START, pos):
            pos = _consume_native_cdata(xml, top, pos, stack, tokens)
            continue

        # CDATA-like prefix at a content position is plain text;
        # the narrower regex keeps legitimate tags like <cdata> intact
        prefix_match = CDATA_TEXT_PREFIX_RE.match(xml, pos)
        if prefix_match:
            _append_text_segment(top, prefix_match.group())
            pos = prefix_match.end()
            continue

        parsed = _parse_xml_tag(xml, pos)
        if parsed is None:
            _append_text_segment(top, '<')
            pos += 1
            continue

        kind, name, full, s, e = parsed

        if kind == 'comment':
            _append_text_segment(top, _fix_comment(full), raw=True)
            pos = e

        elif kind == 'self_close':
            _, _, fixed_tag = _fix_start_tag(full, self_close=True)
            _append_text_segment(top, fixed_tag, raw=True)
            pos = e

        elif kind == 'start':
            # Attributes are parsed and standardized at node creation
            _, fixed_attrs, fixed_tag = _fix_start_tag(full, self_close=False)
            node = Node(name, fixed_tag, top, attrs=fixed_attrs)
            top.children.append(node)

            cdata_match = _match_cdata_open(xml, e)
            if cdata_match is not None:
                # CDATA start tag: start tag + CDATA prefix as a whole;
                # the text_tags membership check is intentionally skipped
                prefix, prefix_end = cdata_match
                node.is_text_tag = True
                node.cdata_start = True
                node.cdata_open_prefix = prefix
                node.content_pos = prefix_end
                node.in_cdata = True
            elif name in text_tags_set:
                # Pure text tag
                node.is_text_tag = True
                node.cdata_start = False
                node.content_pos = e
                node.in_cdata = False

            stack.append(node)
            pos = e

        else:  # 'end'
            handled = _handle_end_tag(stack, name, s, tokens, closes_of)
            if not handled:
                _append_text_segment(stack[-1], full)
            pos = e

    while len(stack) > 1:
        stack.pop().auto_closed = True

    _split_auto_closed_same_name(doc)

    return _serialize_node(doc)


def get_xml_tag_text(value) -> str:
    """
    Extract text content from xmltodict parsing results, handling all edge value formats.

    Supported value types:
    - None / empty value → returns empty string
    - Plain string → returns the string directly
    - Dict with #text key (tag with attributes) → returns #text value
    - List of tags → takes first element and processes by above rules
    - Any other type → returns empty string

    Args:
        value: Value extracted from xmltodict parse result for a tag

    Returns:
        Clean text content string
    """
    if value is None:
        return ''
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        if not value:
            return ''
        return get_xml_tag_text(value[0])
    if isinstance(value, dict):
        return value.get('#text', '')
    return ''


# ------------------------------
# Internal Helpers
# ------------------------------
def _tokenize(xml: str) -> List[Token]:
    tokens: List[Token] = []
    pos = 0
    n = len(xml)

    while pos < n:
        lt = xml.find('<', pos)
        if lt == -1:
            break

        # Skip CDATA-like prefixes so their spans never produce junk tags that
        # would swallow real closing tags and pollute the closing index
        prefix_match = CDATA_TEXT_PREFIX_RE.match(xml, lt)
        if prefix_match:
            pos = prefix_match.end()
            continue

        parsed = _parse_xml_tag(xml, lt)
        if parsed is None:
            pos = lt + 1
            continue

        kind, name, full, s, e = parsed
        tokens.append(Token(kind, name, s, e))
        pos = e

    return tokens


def _index_tokens(tokens: List[Token]) -> Tuple[Dict[str, List[int]], Dict[str, List[int]]]:
    opens_of: Dict[str, List[int]] = {}
    closes_of: Dict[str, List[int]] = {}

    for idx, token in enumerate(tokens):
        if token.kind == 'start':
            opens_of.setdefault(token.name, []).append(idx)
        elif token.kind == 'end':
            closes_of.setdefault(token.name, []).append(idx)

    return opens_of, closes_of


def _next_token_index(tokens: List[Token], pos: int) -> int:
    lo, hi = 0, len(tokens)
    while lo < hi:
        mid = (lo + hi) // 2
        if tokens[mid].start < pos:
            lo = mid + 1
        else:
            hi = mid
    return lo


def _next_close_after_pos(
    tokens: List[Token],
    closes_of: Dict[str, List[int]],
    name: str,
    pos: int
) -> Optional[int]:
    lst = closes_of.get(name)
    if not lst:
        return None

    lo, hi = 0, len(lst)
    while lo < hi:
        mid = (lo + hi) // 2
        if tokens[lst[mid]].start <= pos:
            lo = mid + 1
        else:
            hi = mid

    if lo >= len(lst):
        return None

    return tokens[lst[lo]].start


def _can_close_later(
    node: Node,
    pos: int,
    tokens: List[Token],
    closes_of: Dict[str, List[int]]
) -> bool:
    next_own = _next_close_after_pos(tokens, closes_of, node.name, pos)
    if next_own is None:
        return False

    next_ancestor = None
    parent = node.parent
    while parent is not None and parent.name != 'document':
        nxt = _next_close_after_pos(tokens, closes_of, parent.name, pos)
        if nxt is not None and (next_ancestor is None or nxt < next_ancestor):
            next_ancestor = nxt
        parent = parent.parent

    return next_ancestor is None or next_own < next_ancestor


def _is_ancestor_name(node: Node, name: str) -> bool:
    parent = node.parent
    while parent is not None and parent.name != 'document':
        if parent.name == name:
            return True
        parent = parent.parent
    return False


def _handle_end_tag(
    stack: List[Node],
    name: str,
    pos: int,
    tokens: List[Token],
    closes_of: Dict[str, List[int]]
) -> bool:
    """
    Process an unmatched/end tag.

    Returns:
        True if this closing tag was consumed as an explicit close,
        an implicit-close signal, or an ignored mistyped close.
        False if this closing tag is outside the tag stack and should be
        preserved as plain text.
    """
    match_idx = None
    for idx in range(len(stack) - 1, 0, -1):
        if stack[idx].name == name:
            match_idx = idx
            break

    is_abnormal_root_close = False
    if match_idx == 1:
        close_indices = closes_of.get(name)
        if close_indices:
            last_close_pos = tokens[close_indices[-1]].start
            if pos < last_close_pos:
                match_idx = None
                is_abnormal_root_close = True

    if match_idx is not None:
        # Nodes above the matched one are implicitly closed
        while len(stack) - 1 > match_idx:
            stack.pop().auto_closed = True
        node = stack.pop()
        node.explicit_close = True
        return True

    if is_abnormal_root_close:
        # 异常根关闭：可以弹出已经无法在上级关闭前正常关闭的节点，
        # 但绝不在这里关闭根节点。如果已经回到根层级，则把该关闭标签
        # 当作文本保留，便于序列化时转义为 &lt;/root&gt;。
        while len(stack) > 2:
            top = stack[-1]
            if _can_close_later(top, pos, tokens, closes_of):
                return True
            top.auto_closed = True
            stack.pop()
        return False

    if len(stack) <= 2:
        return False

    # Unmatched closing tag: pop tops that can no longer be
    # closed by their own closing tag before any ancestor close; stop
    # conservatively at the root node
    while len(stack) > 2:
        top = stack[-1]
        if _can_close_later(top, pos, tokens, closes_of):
            break
        top.auto_closed = True
        stack.pop()

    return True

def _match_cdata_open(xml: str, pos: int) -> Optional[Tuple[str, int]]:
    match = CDATA_PREFIX_RE.match(xml, pos)
    if match:
        return match.group(), match.end()
    return None


def _consume_text_tag(
    xml: str,
    node: Node,
    tokens: List[Token],
    closes_of: Dict[str, List[int]]
) -> int:
    """
    Consume the content of a pure text tag (name in text_tags and no CDATA opening
    prefix after its start tag).

    Content stays in plain-text mode the whole time: any CDATA-like marker is kept
    as ordinary text and entity-escaped on serialization. Tag-like tokens
    inside the content are either absorbed as text (own close still reachable
    before any ancestor close) or trigger an implicit close of this text tag.
    """
    tname = node.name
    n = len(xml)
    pos = node.content_pos

    while pos < n:
        lt = xml.find('<', pos)
        if lt == -1:
            _append_text_segment(node, xml[pos:n])
            node.auto_closed = True
            return n

        if lt > pos:
            _append_text_segment(node, xml[pos:lt])

        # Any CDATA-like opening marker is plain text here
        prefix_match = CDATA_TEXT_PREFIX_RE.match(xml, lt)
        if prefix_match:
            _append_text_segment(node, prefix_match.group())
            pos = prefix_match.end()
            continue

        parsed = _parse_xml_tag(xml, lt)
        if parsed is None:
            _append_text_segment(node, '<')
            pos = lt + 1
            continue

        kind, name, full, s, e = parsed

        if kind == 'end':
            if name == tname:
                node.explicit_close = True
                return e
            if _is_ancestor_name(node, name):
                node.auto_closed = True
                return lt
            if _can_close_later(node, lt, tokens, closes_of):
                _append_text_segment(node, full)
                pos = e
                continue
            node.auto_closed = True
            return lt

        if kind == 'start':
            if name == tname:
                # Same-name start tag: this text tag was left unclosed
                node.auto_closed = True
                return lt
            if _is_ancestor_name(node, name):
                node.auto_closed = True
                return lt
            if _can_close_later(node, lt, tokens, closes_of):
                _append_text_segment(node, full)
                pos = e
                continue
            node.auto_closed = True
            return lt

        # Comment / self-closing token
        if _can_close_later(node, lt, tokens, closes_of):
            _append_text_segment(node, full)
            pos = e
            continue

        node.auto_closed = True
        return lt

    node.auto_closed = True
    return n


def _consume_native_cdata(
    xml: str,
    node: Node,
    pos: int,
    stack: List[Node],
    tokens: List[Token],
) -> int:
    """
    Consume a native legal CDATA section found in structural content.

    The whole `<![CDATA[...]]>` segment is preserved as-is. If no `]]>` can be found,
    the closing tag of a node currently on the stack is searched,
    trailing suspected CDATA-end residue is removed and the segment is closed properly.
    """
    n = len(xml)
    content_start = pos + len(CDATA_START)

    end = xml.find(CDATA_END, content_start)
    if end != -1:
        _append_text_segment(node, xml[content_start:end], is_cdata=True)
        return end + len(CDATA_END)

    stack_names = {item.name for item in stack}
    ti = _next_token_index(tokens, content_start)
    while ti < len(tokens):
        kind, name, s, e = tokens[ti]
        if kind == 'end' and name in stack_names:
            raw = _strip_trailing_cdata_ends(xml[content_start:s])
            _append_text_segment(node, raw, is_cdata=True)
            return s
        ti += 1

    raw = _strip_trailing_cdata_ends(xml[content_start:n])
    _append_text_segment(node, raw, is_cdata=True)
    return n


def _consume_cdata_start_tag(
    xml: str,
    node: Node,
    tokens: List[Token],
    closes_of: Dict[str, List[int]]
) -> int:
    """
    Consume the content of a CDATA start tag (start tag followed by a compatible
    CDATA opening prefix).

    Closing priority:
    1. exact combo `]]></name>`
    2. suspected CDATA-end residue before `</name>`
    3. normal text-tag closing rules
    4. boundary/EOF fallback
    """
    tname = node.name
    n = len(xml)
    pos = node.content_pos
    close_tag = f'</{tname}>'
    combo = CDATA_END + close_tag

    # Priority 1: exact combo close anywhere in the remaining content.
    # CDATA may legally contain same-name/ancestor tags, so this must win.
    combo_pos = xml.find(combo, pos)
    if combo_pos != -1:
        _append_text_segment(node, xml[pos:combo_pos], is_cdata=True)
        node.explicit_close = True
        node.auto_closed = False
        return combo_pos + len(combo)

    # Priority 2: suspected CDATA-end residue immediately before a normal close.
    search_pos = pos
    while True:
        close_pos = xml.find(close_tag, search_pos)
        if close_pos == -1:
            break

        raw = xml[pos:close_pos]
        if TRAILING_CDATA_END_RE.search(raw):
            _append_text_segment(
                node,
                _strip_trailing_cdata_ends(raw),
                is_cdata=True,
            )
            node.explicit_close = True
            node.auto_closed = False
            return close_pos + len(close_tag)

        search_pos = close_pos + len(close_tag)

    # Priority 3/4: fallback to text-tag rules and boundary signals.
    scan_pos = pos
    content_end = n
    close_end = n
    explicit = False

    while scan_pos < n:
        ti = _next_token_index(tokens, scan_pos)
        if ti >= len(tokens):
            break

        kind, name, s, e = tokens[ti]

        # Normal own closing tag.
        if kind == 'end' and name == tname:
            content_end = s
            close_end = e
            explicit = True
            break

        boundary = False

        if kind == 'end':
            if _is_ancestor_name(node, name):
                boundary = True
            elif not _can_close_later(node, s, tokens, closes_of):
                boundary = True

        elif kind == 'start':
            if name == tname:
                boundary = True
            elif _is_ancestor_name(node, name):
                boundary = True
            elif not _can_close_later(node, s, tokens, closes_of):
                boundary = True

        else:
            if not _can_close_later(node, s, tokens, closes_of):
                boundary = True

        if boundary:
            content_end = s
            close_end = s
            explicit = False
            break

        scan_pos = e

    raw = _strip_trailing_cdata_ends(xml[pos:content_end])
    _append_text_segment(node, raw, is_cdata=True)

    node.explicit_close = explicit
    node.auto_closed = not explicit

    return close_end if explicit else content_end


def _append_text_segment(
    node: Node,
    text: str,
    is_cdata: bool = False,
    raw: bool = False
) -> None:
    if not text and not is_cdata:
        return

    segments = node.segments if node.is_text_tag else node.children

    if segments:
        last = segments[-1]
        if (
            isinstance(last, TextSegment)
            and last.is_cdata == is_cdata
            and last.raw == raw
        ):
            last.text += text
            return

    segment = TextSegment(text, is_cdata=is_cdata, raw=raw)
    if node.is_text_tag:
        node.segments.append(segment)
    else:
        node.children.append(segment)


def _split_auto_closed_same_name(node: Node) -> None:
    for child in list(node.children):
        if isinstance(child, Node):
            _split_auto_closed_same_name(child)

    if (
        not node.auto_closed
        or node.parent is None
        or node.parent.name == 'document'
    ):
        return

    idx = None
    for i, child in enumerate(node.children):
        if isinstance(child, Node) and child.name == node.name:
            idx = i
            break

    if idx is None:
        return

    moved = node.children[idx:]
    node.children = node.children[:idx]

    parent = node.parent
    try:
        pos = parent.children.index(node)
    except ValueError:
        return

    parent.children[pos + 1:pos + 1] = moved

    for item in moved:
        if isinstance(item, Node):
            item.parent = parent
            _split_auto_closed_same_name(item)


def _serialize_node(node: Node) -> str:
    if node.name == 'document':
        return ''.join(_serialize_child(child) for child in node.children)

    parts = [node.start_tag]

    if node.is_text_tag:
        if node.cdata_start and not node.segments:
            parts.append(CDATA_START + CDATA_END)
        else:
            for segment in node.segments:
                parts.append(_serialize_segment(segment))
    else:
        for child in node.children:
            parts.append(_serialize_child(child))

    parts.append(f'</{node.name}>')
    return ''.join(parts)


def _serialize_child(child: Any) -> str:
    if isinstance(child, Node):
        return _serialize_node(child)
    return _serialize_segment(child)


def _serialize_segment(segment: TextSegment) -> str:
    if segment.raw:
        return segment.text
    if segment.is_cdata:
        return CDATA_START + _escape_cdata_ends(segment.text) + CDATA_END
    return _escape_xml_entity(segment.text)


def _escape_cdata_ends(s: str) -> str:
    """
    Escape all bare CDATA_END (]]>) sequences in string to valid embedded format.
    Avoids double escaping existing properly escaped CDATA_END sequences.
    """
    parts = []
    i = 0
    n = len(s)

    while i < n:
        if s.startswith(ESCAPED_CDATA_END, i):
            parts.append(ESCAPED_CDATA_END)
            i += len(ESCAPED_CDATA_END)
        elif s.startswith(CDATA_END, i):
            parts.append(ESCAPED_CDATA_END)
            i += len(CDATA_END)
        else:
            j = i
            while j < n:
                if s.startswith(ESCAPED_CDATA_END, j) or s.startswith(CDATA_END, j):
                    break
                j += 1
            parts.append(s[i:j])
            i = j

    return ''.join(parts)


def _escape_xml_entity(s: str) -> str:
    """
    Escape special characters (<, >, &) in normal XML text content, preserving valid existing XML entities.
    """
    parts = []
    i = 0
    n = len(s)

    while i < n:
        next_positions = (
            s.find('<', i),
            s.find('>', i),
            s.find('&', i),
        )

        if next_positions == (-1, -1, -1):
            parts.append(s[i:])
            break

        next_pos = min(p for p in next_positions if p != -1)
        parts.append(s[i:next_pos])
        i = next_pos

        if s[i] == '<':
            parts.append('&lt;')
            i += 1
        elif s[i] == '>':
            parts.append('&gt;')
            i += 1
        else:
            entity_match = XML_ENTITY_RE.match(s, i)
            if entity_match:
                parts.append(entity_match.group())
                i = entity_match.end()
            else:
                parts.append('&amp;')
                i += 1

    return ''.join(parts)


def _escape_attr_value(value: str) -> str:
    """
    Escape characters that would break a double-quoted XML attribute value
    (<, >, "), preserving already valid XML entities.
    """
    parts = []
    i = 0
    n = len(value)

    while i < n:
        c = value[i]
        if c == '<':
            parts.append('&lt;')
            i += 1
        elif c == '>':
            parts.append('&gt;')
            i += 1
        elif c == '"':
            parts.append('&quot;')
            i += 1
        elif c == '&':
            entity_match = XML_ENTITY_RE.match(value, i)
            if entity_match:
                parts.append(entity_match.group())
                i = entity_match.end()
            else:
                parts.append('&amp;')
                i += 1
        else:
            parts.append(c)
            i += 1

    return ''.join(parts)


def _strip_trailing_cdata_ends(s: str) -> str:
    match = TRAILING_CDATA_END_RE.search(s)
    if match:
        return s[:match.start()]
    return s


def _clean_attr_name(raw: str) -> str:
    """
    Normalize a raw attribute name: drop stray quotes and any character not
    allowed inside an XML name. An empty result means the
    attribute must be discarded.
    """
    filtered = ''.join(c for c in raw if _is_xml_name_char(c))

    start = 0
    while start < len(filtered) and not _is_xml_name_start_char(filtered[start]):
        start += 1

    name = filtered[start:]
    return name if _is_valid_tag_name(name) else ''


def _fix_comment(comment: str) -> str:
    """
    Normalize a comment token to a well-formed XML comment.

    - Unterminated comments are closed with '-->'.
    - Illegal '--' inside comment body is sanitized to '- -'.
    - A trailing '-' is padded with a space.
    """
    if not comment.startswith('<!--'):
        return comment

    body = comment[4:]

    if body.endswith('-->'):
        body = body[:-3]

    if '--' in body:
        body = body.replace('--', '- -')

    if body.endswith('-'):
        body += ' '

    return f'<!--{body}-->'


def _parse_and_fix_attributes(inner: str) -> Dict[str, str]:
    """
    Parse the raw attribute region of a start tag and produce standardized
    attributes:

    - attribute values with unclosed quotes are closed at the tag end;
    - attribute names are cleaned of stray quotes and illegal characters,
      empty names are discarded;
    - unquoted values are captured up to the next whitespace / tag end;
    - the first occurrence wins for duplicated attribute names.
    """
    attrs: Dict[str, str] = {}
    i = 0
    n = len(inner)

    while i < n:
        while i < n and inner[i].isspace():
            i += 1
        if i >= n:
            break
        if inner[i] == '=':
            # Stray '=' without an attribute name, skip it
            i += 1
            continue

        # Raw attribute name token: up to whitespace or '='
        j = i
        while j < n and not inner[j].isspace() and inner[j] != '=':
            j += 1
        raw_name = inner[i:j]
        i = j
        name = _clean_attr_name(raw_name)

        k = i
        while k < n and inner[k].isspace():
            k += 1

        value = ''
        if k < n and inner[k] == '=':
            vpos = k + 1
            q = vpos
            while q < n and inner[q].isspace():
                q += 1
            had_space = q > vpos

            if q < n and inner[q] in ('"', "'"):
                quote = inner[q]
                close = inner.find(quote, q + 1)
                if close != -1:
                    # 如果 `=` 后出现空格，且引号片段后面紧跟 `=`，
                    # 那么这个引号片段更可能是下一个属性名（如 `A= "B"="x"`），
                    # 当前属性的值为空，而不是把引号片段当成值。
                    is_name_like = False
                    if had_space:
                        after = close + 1
                        while after < n and inner[after].isspace():
                            after += 1
                        is_name_like = after < n and inner[after] == '='
                    if is_name_like:
                        value = ''
                        i = q
                    else:
                        value = inner[q + 1:close]
                        i = close + 1
                else:
                    value = inner[q + 1:]
                    i = n
            elif q >= n:
                value = ''
                i = n
            else:
                token_end = q
                while token_end < n and not inner[token_end].isspace():
                    token_end += 1

                token = inner[q:token_end]

                if had_space and '=' in token:
                    # 形如 `A= A=""`：A 是空值，后面的 A="" 是下一个属性。
                    value = ''
                    i = q
                else:
                    value = token
                    i = token_end
        else:
            # Attribute without '=': keep it with an empty value
            i = k

        if name and name not in attrs:
            attrs[name] = value

    return attrs


def _fix_start_tag(full: str, self_close: bool) -> Tuple[str, Dict[str, str], str]:
    """
    Parse a raw start tag string and rebuild it as a well-formed tag with
    standardized attributes.

    Returns (tag_name, fixed_attributes, fixed_tag_string).
    """
    match = TAG_NAME_RE.match(full, 1)
    name = match.group() if match else full[1:].strip()

    end = len(full) - 1 if full.endswith('>') else len(full)

    inner_end = end
    if self_close:
        k = end - 1
        while k > 0 and full[k].isspace():
            k -= 1
        if k > 0 and full[k] == '/':
            inner_end = k

    inner = full[1 + len(name):inner_end]
    attrs = _parse_and_fix_attributes(inner)

    parts = [name]
    for key, value in attrs.items():
        parts.append(f'{key}="{_escape_attr_value(value)}"')
    tag = '<' + ' '.join(parts) + ('/>' if self_close else '>')

    return name, attrs, tag


def _parse_xml_tag(
    xml: str,
    pos: int
) -> Optional[Tuple[str, Optional[str], str, int, int]]:
    """
    Try to parse an XML tag (comment, opening, closing, self-closing) from given position.

    Returns:
        Tuple (tag_type, name_or_None, full_tag_str, start_pos, end_pos) on success, None on failure.
        Tag types: 'comment', 'end' (closing tag), 'start' (opening tag), 'self_close' (self-closing tag)

    Attribute values are scanned quote-aware. A '>' inside an open quote only ends
    the tag when no closing quote appears before the next '<' (i.e. the quote is
    unclosed, design); this keeps valid values like `title="a>b"` intact
    while recovering inputs like `name="test></item>`. An unterminated quote at EOF
    makes the tag extend to the end of the string.
    """
    if not xml or pos >= len(xml) or xml[pos] != '<':
        return None

    n = len(xml)
    i = pos

    # 1. Comment tag: <!-- ... --> (unterminated comments close at the next '<')
    if xml.startswith('<!--', i):
        end = xml.find('-->', i + 4)
        if end == -1:
            nxt = xml.find('<', i + 4)
            if nxt == -1:
                return ('comment', None, xml[i:], i, n)
            return ('comment', None, xml[i:nxt], i, nxt)
        end += 3
        return ('comment', None, xml[i:end], i, end)

    # 2. Closing tag: </name> (attributes, if any, are dropped on serialization)
    if xml.startswith('</', i):
        end = xml.find('>', i + 2)
        if end == -1:
            return None
        inner = xml[i + 2:end].strip()
        match = TAG_NAME_RE.match(inner)
        if not match:
            return None
        name = match.group()
        return ('end', name, xml[i:end + 1], i, end + 1)

    # 3. Opening or self-closing tag: <name ...> / <name .../>
    j = i + 1
    match = TAG_NAME_RE.match(xml, j)
    if not match:
        return None

    name = match.group()
    j = match.end()

    # Reject malformed candidates: the character glued directly to the tag
    # name must be able to start a valid tag suffix (whitespace, attribute
    # syntax or the tag terminator). Otherwise the "tag" would swallow the
    # following real tag (e.g. `<B</C>` hiding `</C>`, `<B²</A>`) and
    # corrupt the closing index; callers degrade it to plain text instead.
    if j < n and not (xml[j].isspace() or xml[j] in '>/'):
        return None

    quote_char: Optional[str] = None
    while j < n:
        c = xml[j]

        if quote_char is not None:
            if c == quote_char:
                quote_char = None
            elif c == '>':
                # '>' inside an open quote: it ends the tag only when no closing
                # quote shows up before the next '<' (unclosed attribute quote)
                nxt_lt = xml.find('<', j + 1)
                region_end = n if nxt_lt == -1 else nxt_lt
                if xml.find(quote_char, j + 1, region_end) == -1:
                    return ('start', name, xml[i:j + 1], i, j + 1)
            j += 1
            continue

        if c == '"' or c == "'":
            quote_char = c
        elif c == '>':
            full_tag = xml[i:j + 1]
            k = j - 1
            while k > i and xml[k].isspace():
                k -= 1
            if k > i and xml[k] == '/':
                return ('self_close', name, full_tag, i, j + 1)
            return ('start', name, full_tag, i, j + 1)
        elif c.isspace() or c in '=/':
            pass
        elif _is_xml_name_char(c):
            pass
        else:
            return None

        j += 1

    if quote_char is not None:
        # Unterminated attribute quote at EOF: the tag extends to the end
        return ('start', name, xml[i:], i, n)

    return None


def _parsed_dict_has_nested_text_tags(
    parsed: Dict[str, Any],
    text_tags_set: Set[str]
) -> bool:
    def _value_has_children(value) -> bool:
        if isinstance(value, dict):
            for key in value:
                if not key.startswith('@') and key != '#text':
                    return True
        elif isinstance(value, list):
            for item in value:
                if _value_has_children(item):
                    return True
        return False

    def _check(obj) -> bool:
        if isinstance(obj, dict):
            for key, value in obj.items():
                if key in text_tags_set:
                    if _value_has_children(value):
                        return True
                else:
                    if _check(value):
                        return True
        elif isinstance(obj, list):
            for item in obj:
                if _check(item):
                    return True
        return False

    return _check(parsed)
